def timeline(song, start=0.0):
    """[(時刻, MIDI番号)] を返す。"""
    t, out = start, []
    for midi, beats in song["notes"]:
        out.append((t, midi))
        t += beats * song["unit"]
    return out, t


def accompaniment(song, start=0.0):
    """伴奏の [(時刻, MIDI番号)]。伴奏のない曲は空。"""
    return [(start + beat * song["unit"], midi) for beat, midi in song.get("bass", [])]


def pitches(song):
    return [n for n, _ in song["notes"]]
